 expect(Math.abs(box!.x+box!.width/2-view.width/2)).toBeLessThan(2);expect(Math.abs(box!.y+box!.height/2-view.height/2)).toBeLessThan(2)
 await page.screenshot({path:'../build/screenshots/confirm.png'})
