 await expect(page.getByRole('button',{name:'Excluir registro'})).toBeVisible()
 await page.getByRole('button',{name:'Trocar arquivo'}).click()
 await expect(modal).toContainText('Abrir outro arquivo?');await modal.getByRole('button',{name:'Cancelar'}).click();await expect(modal).toBeHidden()
 await page.getByRole('button',{name:'Trocar arquivo'}).click();await modal.getByRole('button',{name:'Abrir outro arquivo'}).click()
 await expect(modal).toContainText('O que fazer com o registro deste arquivo?')
 await expect(modal.getByRole('button')).toHaveText(['Cancelar','Manter registro','Excluir registro'])
 await modal.getByRole('button',{name:'Cancelar'}).click();await expect(modal).toBeHidden()
 await expect(page.getByRole('alert')).toHaveCount(0);await expect(page.getByText('relato-feira.wav')).toBeVisible()
 await page.getByRole('button',{name:'Manter registro e trocar de arquivo'}).click()
 await expect(modal).toContainText('Manter o registro');await modal.getByRole('button',{name:'Cancelar'}).click()
